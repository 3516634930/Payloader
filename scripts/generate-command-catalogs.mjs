const zhEn = (zh, en) => ({ zh, en });

const psQuote = value => `'${String(value).replace(/'/g, "''")}'`;

const uniqueSorted = values => [...new Set(values)].sort((a, b) => a.localeCompare(b, 'en'));

const commandItem = (name, command, description, platform = 'all') => ({
  name: typeof name === 'string' ? name : zhEn(name.zh, name.en),
  command,
  description: typeof description === 'string' ? description : zhEn(description.zh, description.en),
  platform,
});

const powerShellScript = String.raw`
$ErrorActionPreference = 'Stop'
Get-Command -CommandType Cmdlet,Function,Alias,Filter -All |
  Sort-Object CommandType, Source, Name -Unique |
  ForEach-Object {
    [pscustomobject]@{
      Name = [string]$_.Name
      CommandType = [string]$_.CommandType
      Source = [string]$_.Source
      ModuleName = [string]$_.ModuleName
      Version = if ($_.Version) { [string]$_.Version } else { '' }
    }
  } |
  ConvertTo-Json -Depth 4 -Compress
`;

const rawPowerShellCommands = JSON.parse(execFileSync('powershell.exe', [
  '-NoProfile',
  '-ExecutionPolicy',
  'Bypass',
  '-Command',
  powerShellScript,
], {
  encoding: 'utf8',
  maxBuffer: 20 * 1024 * 1024,
}));

const powerShellCommands = (Array.isArray(rawPowerShellCommands) ? rawPowerShellCommands : [rawPowerShellCommands])
  .filter(item => item?.Name)
  .map(item => ({
    name: item.Name,
    commandType: item.CommandType || 'Command',
    source: item.Source || item.ModuleName || '',
    version: item.Version || '',
  }));

const powerShellCatalog = (commandType, id, zhName, enName, descriptionZh, descriptionEn) => {
  const commands = powerShellCommands
    .filter(item => item.commandType === commandType)
    .sort((a, b) => `${a.source}\0${a.name}`.localeCompare(`${b.source}\0${b.name}`, 'en'))
    .map(item => {
      const source = item.source || 'Shell/Session';
      const helpCommand = commandType === 'Alias'
        ? `Get-Alias -Name ${psQuote(item.name)} | Format-List *`
        : `Get-Help ${psQuote(item.name)} -Full`;
      const typeZh = commandType === 'Alias' ? '别名' : commandType === 'Function' ? '函数' : 'Cmdlet';
      return commandItem(
        zhEn(`${item.name} (${source})`, `${item.name} (${source})`),
        helpCommand,
        zhEn(
          `PowerShell ${typeZh}索引项；来源：${source}。该条目只打开帮助或别名信息，不直接执行原命令。`,
          `PowerShell ${commandType} index entry from ${source}. This entry opens help or alias metadata instead of executing the command.`
        ),
        'windows'
      );
    });

  return {
    id,
    name: zhEn(zhName, enName),
    description: zhEn(descriptionZh, descriptionEn),
    category: zhEn('PowerShell 全命令索引', 'PowerShell Full Command Index'),
    installation: zhEn('由 scripts/generate-command-catalogs.mjs 在当前 Windows PowerShell 环境中通过 Get-Command -All 生成。', 'Generated by scripts/generate-command-catalogs.mjs from the current Windows PowerShell environment using Get-Command -All.'),
    commands,
    references: [
      'https://learn.microsoft.com/en-us/powershell/module/microsoft.powershell.core/get-command',
      'https://learn.microsoft.com/en-us/powershell/module/microsoft.powershell.core/get-help',
    ],
  };
};

